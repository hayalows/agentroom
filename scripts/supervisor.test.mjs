import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import {readState,fields,reviewVerdict} from './room-state.mjs';
import {gateBank,csv} from './bank-gate.mjs';
const root=fs.mkdtempSync(path.join(os.tmpdir(),'room-supervisor-')),goal='test-bank',dir=path.join(root,'goals',goal);
const put=(p,s)=>{const f=path.join(dir,p);fs.mkdirSync(path.dirname(f),{recursive:true});fs.writeFileSync(f,s);};
try{
  assert.equal(fields('\uFEFFagent: deepseek\nstatus: in-progress').agent,'deepseek');
  assert.deepEqual(csv('a,b\n"x,y","a""b"\n'),[{a:'x,y',b:'a"b'}]);
  assert.throws(()=>csv('a,b\n1\n'));
  put('ROSTER.md','| Slug | Bank |\n| --- | --- |\n| bank-a | Bank A |\n| bank-b | Bank B |\n');
  put('board/deepseek.md','- 2026-11-25T12:00:00Z JOINED\nTO codex: Check the model\n');
  put('board/codex.md','- 2026-11-25T12:02:00Z CHECK-IN\nACK deepseek: received\n');
  put('claims/bank-a.md','\uFEFFagent: deepseek\nstatus: needs-review\n');
  const now=Date.parse('2026-11-25T12:20:00Z');
  let s=readState(root,goal,now);
  assert.equal(s.agents.length,2);assert.equal(s.tasks.length,2);assert.equal(s.tasks[0].owner,'deepseek');
  assert.equal(s.pending.length,0);assert.equal(s.agents.find(a=>a.id==='deepseek').activity,'quiet-15m');
  assert.deepEqual(s.actionable.codex.review,['bank-a']);assert(s.actionable.deepseek.claim.includes('bank-b'));
  assert.equal(reviewVerdict('Reviewer: codex. Verdict: CHANGES REQUIRED (reason).'),'CHANGES');
  assert.equal(reviewVerdict('**Verdict:** PASS'),'PASS');
  put('reviews/codex-of-deepseek-bank-a.md','Reviewer: codex. Verdict: CHANGES REQUIRED (reason).');
  const repair=readState(root,goal,now);assert.deepEqual(repair.actionable.deepseek.repair,['bank-a']);assert.equal(repair.actionable.deepseek.next,'repair');
  fs.unlinkSync(path.join(dir,'reviews/codex-of-deepseek-bank-a.md'));
  put('claims/bank-a-takeover.md','agent: codex\nstatus: in-progress\n');
  assert.equal(readState(root,goal,now).tasks[0].status,'ownership-conflict');
  fs.unlinkSync(path.join(dir,'claims/bank-a-takeover.md'));
  const task=s.tasks[0], header='bank,period,statement,line_item,value,unit,source_id,page,status,notes,scenario\n';
  const pairs=[['total_assets',10],['total_liabilities',7],['total_equity',3],['net_interest_income',4],['interest_income',6],['interest_expense',2],['profit_after_tax',2],['profit_before_tax',3],['income_tax',1]];
  const rows=(period,scenario)=>pairs.map(([key,v])=>['bank-a',period,'statement',key,v,'GHS millions','source','1',scenario?'estimated':'reported','',scenario].join(',')).join('\n')+'\n';
  let hist=header+[2021,2022,2023,2024,2025].map(y=>rows('FY'+y,'')).join('');
  let forecast=header+['base','downside','upside'].flatMap(s=>[2026,2027,2028,2029,2030].map(y=>rows('FY'+y+'E',s))).join('');
  for(const file of ['README.md','sources.md','checks.md'])put('banks/bank-a/'+file,'test fixture');
  put('banks/bank-a/financials.csv',hist);put('banks/bank-a/forecast.csv',forecast);
  put('banks/bank-a/assumptions.json','{"macro":"macro.csv"}');put('banks/bank-a/model.py','# reads macro.csv');put('sector/macro-assumptions/macro.csv','fixture');
  const pass=await gateBank(root,goal,task);assert.equal(pass.status,'core-checks-pass');assert.equal(pass.checks.arithmetic.score,100);
  put('banks/bank-a/forecast.csv',forecast.replace('total_assets,10','total_assets,11'));
  const fail=await gateBank(root,goal,task);assert.equal(fail.status,'failed');assert.equal(fail.checks.arithmetic.score,0);assert.notEqual(pass.fingerprint,fail.fingerprint);
  put('banks/bank-a/forecast.csv',forecast);put('sector/macro-assumptions/macro.csv','changed fixture');
  assert.notEqual((await gateBank(root,goal,task)).macroFingerprint,pass.macroFingerprint);
  fs.unlinkSync(path.join(dir,'banks/bank-a/forecast.csv'));assert.equal((await gateBank(root,goal,task)).status,'incomplete');
  console.log('PASS: discovery, BOM, chronology, advisory queue, conflict detection, CSV, evidence gate pass/fail, fingerprints, incomplete model');
}finally{fs.rmSync(root,{recursive:true,force:true});}
