#!/usr/bin/env python3
"""Build financials.csv and checks_history.md for Absa Bank Ghana PLC (bank-only). Standard library only.

Input: ../../assistance/remaining-banks/absa-primary-source-pack-codex.csv, 300 rows transcribed by the independent agent codex from the official
Absa Ghana statements (see sources.md). The owner could NOT open the Absa PDFs (automated access is refused), so the owner did not re-read the
source pages. This script copies the rows unchanged (the pack is the owner's only source), then re-runs the statement identities.
Run:  python build_financials.py
"""
import csv, os
HERE = os.path.dirname(os.path.abspath(__file__))
PACK = os.path.join(HERE, "..", "..", "assistance", "remaining-banks", "absa-primary-source-pack-codex.csv")
rows = list(csv.DictReader(open(PACK, encoding="utf-8")))
cols = ["bank", "period", "statement", "line_item", "value", "unit", "source_id", "page", "status", "notes"]
with open(os.path.join(HERE, "financials.csv"), "w", newline="", encoding="utf-8") as f:
    w = csv.DictWriter(f, fieldnames=cols, lineterminator="\n")
    w.writeheader()
    for r in rows:
        w.writerow({k: r[k] for k in cols})
V = {(r["period"], r["line_item"]): float(r["value"]) for r in rows if r["value"] != ""}
PER = ["FY2021", "FY2022", "FY2023", "FY2024", "FY2025", "9M-2025", "9M-2026"]
L = ["# Historical data checks (absa-ghana)", "", "Generated by `build_financials.py` from the codex source pack. Tolerance 0.002 GHS m (rounding of thousands).", "",
     "| Check | Computed | Reported | Difference | Result |", "| --- | --- | --- | --- | --- |"]
fails = 0
def chk(label, a, b, tol=0.002):
    global fails
    ok = abs(a - b) <= tol
    fails += 0 if ok else 1
    L.append(f"| {label} | {a:,.3f} | {b:,.3f} | {a-b:+.3f} | {'PASS' if ok else 'FAIL'} |")
for p in PER:
    g = lambda k: V[(p, k)]
    chk(f"{p}: NII = interest income - interest expense", g("interest_income") - g("interest_expense"), g("net_interest_income"))
    chk(f"{p}: operating income = NII + net fees + trading + other", g("net_interest_income") + g("fee_commission_income") - g("fee_commission_expense") + g("net_trading_income") + g("other_operating_income"), g("total_operating_income"))
    chk(f"{p}: PBT = operating income - impairment - staff - D&A - other", g("total_operating_income") - g("impairment_charge") - g("staff_costs") - g("depreciation_amortisation") - g("other_operating_expenses"), g("profit_before_tax"))
    chk(f"{p}: PAT = PBT - tax", g("profit_before_tax") - g("income_tax"), g("profit_after_tax"))
    chk(f"{p}: asset lines = total assets", g("cash_and_bog_balances") + g("due_from_banks") + g("investment_securities") + g("loans_and_advances_net") + g("property_equipment_intangibles") + g("other_assets"), g("total_assets"))
    chk(f"{p}: liability lines = total liabilities", g("customer_deposits") + g("due_to_banks") + g("borrowings") + g("other_liabilities"), g("total_liabilities"))
    chk(f"{p}: equity lines = total equity", g("stated_capital") + g("retained_earnings") + g("reserves_other"), g("total_equity"))
    chk(f"{p}: assets = liabilities + equity", g("total_liabilities") + g("total_equity"), g("total_assets"))
    chk(f"{p}: reserves_other = statutory + credit risk + other", g("x_statutory_reserve") + g("x_credit_risk_reserve") + g("x_other_reserves"), g("reserves_other"))
L += ["", "## Interim equity roll-forward (column orientation)", "", "| Check | Computed | Reported | Difference | Result |", "| --- | --- | --- | --- | --- |"]
chk("9M-2026: FY2025 equity + PAT + OCI + 3.930 (other, per the pack note) - dividends 1,115 = closing equity", V[("FY2025", "total_equity")] + V[("9M-2026", "profit_after_tax")] + V[("9M-2026", "x_oci")] + 3.930 - V[("9M-2026", "x_dividends_paid")], V[("9M-2026", "total_equity")], 0.005)
L += ["", "The 3.930m 'other' item is quoted from the pack's source note and is not a separate row in the pack (unknown: not seen on the statement by the owner).", "", f"**History check failures: {fails}**", ""]
open(os.path.join(HERE, "checks_history.md"), "w", encoding="utf-8").write("\n".join(L))
print("rows", len(rows), "failures", fails)
