#!/usr/bin/env python3
"""Sector roll-up for goals/ghana-bank-models. Standard library only.

Run:  python rollup.py        writes rollup.md and rollup.csv next to this file.

Includes ONLY banks whose claim status is needs-review or done (work in progress is excluded),
so the totals are a PARTIAL sector until all 23 banks are finished. The coverage table shows how partial.
Bank figures are bank-only (separate) statements, GHS millions. Sector totals are the Bank of Ghana's
aggregate banking-sector figures from sector/macro-assumptions/sector-context.csv.
"""
import csv
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
GOAL = os.path.abspath(os.path.join(HERE, "..", ".."))
BANKS = os.path.join(GOAL, "banks")
CLAIMS = os.path.join(GOAL, "claims")
PERIODS = ["FY2021", "FY2022", "FY2023", "FY2024", "FY2025", "9M-2026"]
FYE = [f"FY{y}E" for y in range(2026, 2031)]
SCEN = ["base", "downside", "upside"]
BIG = ["total_assets", "customer_deposits", "loans_and_advances_net", "total_equity", "profit_after_tax", "operating_income_pre_impairment", "net_interest_income"]


def read_rows(path):
    with open(path, newline="", encoding="utf-8-sig") as f:
        return list(csv.DictReader(f))


def claim(slug):
    p = os.path.join(CLAIMS, slug + ".md")
    owner = status = ""
    if os.path.exists(p):
        for line in open(p, encoding="utf-8-sig"):
            m = re.match(r"^(agent|status):\s*(.*)$", line.strip())
            if m and m.group(1) == "agent" and not owner:
                owner = m.group(2)
            if m and m.group(1) == "status":
                status = m.group(2)
    return owner, status


def roster():
    out = []
    for line in open(os.path.join(GOAL, "ROSTER.md"), encoding="utf-8-sig"):
        m = re.match(r"^\|\s*([a-z0-9-]+)\s*\|\s*(.+?)\s*\|$", line)
        if m and m.group(1) not in ("Slug", "---") and not m.group(1).startswith("-"):
            out.append((m.group(1), m.group(2)))
    return out


def sector_context():
    d = {}
    p = os.path.join(GOAL, "sector", "macro-assumptions", "sector-context.csv")
    for r in read_rows(p):
        d[r["indicator"]] = r
    return d


hist, fc, status_of = {}, {}, {}
included = []
for slug in sorted(os.listdir(BANKS)):
    d = os.path.join(BANKS, slug)
    if not os.path.isdir(d) or slug.startswith("__"):
        continue
    owner, st = claim(slug)
    status_of[slug] = (owner, st)
    if st not in ("needs-review", "done"):
        continue
    f, g = os.path.join(d, "financials.csv"), os.path.join(d, "forecast.csv")
    if not (os.path.exists(f) and os.path.exists(g)):
        continue
    included.append(slug)
    for r in read_rows(f):
        if r["value"] != "":
            hist[(slug, r["period"], r["line_item"])] = float(r["value"])
    for r in read_rows(g):
        if r.get("value", "") != "":
            fc[(slug, r["scenario"], r["period"], r["line_item"])] = float(r["value"])


def H(b, p, i):
    if i == "operating_income_pre_impairment":
        parts = [hist.get((b, p, k)) for k in ("net_interest_income", "fee_commission_income", "fee_commission_expense", "net_trading_income", "other_operating_income")]
        if any(x is None for x in parts):
            return None
        return parts[0] + parts[1] - parts[2] + parts[3] + parts[4]
    return hist.get((b, p, i))


def total(p, item, banks=None):
    vals = [H(b, p, item) for b in (banks or included)]
    got = [v for v in vals if v is not None]
    return sum(got), len(got)


import subprocess, datetime
def _git():
    try:
        return subprocess.run(["git", "-C", GOAL, "rev-parse", "--short", "HEAD"], capture_output=True, text=True, timeout=10).stdout.strip() or "unknown"
    except Exception:
        return "unknown"
stamp = f"Generated {datetime.datetime.now(datetime.timezone.utc).strftime('%Y-%m-%dT%H:%M:%SZ')} from repo commit {_git()}."
accepted = [b for b in included if status_of[b][1] == "done"]
provisional = [b for b in included if status_of[b][1] != "done"]
lines = ["# Sector roll-up (PARTIAL: finished banks only)", "", stamp, f"**Accepted (claim status `done`, {len(accepted)}):** {', '.join(accepted) or 'none'}.", f"**PROVISIONAL (`needs-review`, an independent review may still require changes, {len(provisional)}):** {', '.join(provisional) or 'none'}.", "",
         f"Generated by `sector/sector-rollup/rollup.py`. Banks included ({len(included)}): {', '.join(included)}.",
         "Only banks marked `needs-review` or `done` are included. **This is not the whole sector.** Bank-only statements, GHS millions.", ""]
csv_rows = [["table", "period_or_scenario", "item", "bank", "value", "n_banks_reporting"]]
csv_rows.append(["meta", "generated_from_commit", "", "", _git(), ""])

# ------------------------------------------------------------------ coverage
ctx = sector_context()
lines += ["## 1. Coverage of the banking sector", "",
          "Bank of Ghana sector aggregates are in GHS billions (`sector-context.csv`); bank values converted to billions. 9M-2026 bank balance sheets are at 30 Sep 2026 and are compared with the BoG September 2026 figures (same month). Operating income is recomputed for every bank as net interest income + net fees + trading + other operating income (before impairment), so banks that print a different subtotal stay comparable.", "",
          "| Measure | Period | Included banks (GHS bn) | BoG sector (GHS bn) | Coverage |", "| --- | --- | --- | --- | --- |"]
cov = [("Total assets", "total_assets", "total_assets", "FY2025", "2025-12"), ("Total assets", "total_assets", "total_assets", "9M-2026", "2026-09"),
       ("Customer deposits", "customer_deposits", "total_deposits", "FY2025", "2025-12"), ("Customer deposits", "customer_deposits", "total_deposits", "9M-2026", "2026-09")]
for label, item, ctxkey, per, col in cov:
    s, n = total(per, item)
    sec = float(ctx[ctxkey][col])
    lines.append(f"| {label} | {per} | {s / 1000:,.1f} ({n} banks) | {sec:,.1f} | {s / 1000 / sec * 100:.0f}% |")
    csv_rows.append(["coverage", per, item, "ALL_INCLUDED", f"{s:.3f}" if n else "", n])
lines += ["", "Net loans are not compared: the BoG figure is gross advances and several banks report net loans only.", ""]

# missing banks
ros = roster()
missing = [(s, n) for s, n in ros if s not in included]
lines += [f"### Banks not yet in the roll-up ({len(missing)} of {len(ros)})", "", "| Bank | Owner | Status |", "| --- | --- | --- |"]
for s, n in missing:
    o, st = claim(s)
    lines.append(f"| {s} | {o or '-'} | {st or 'unclaimed'} |")
lines.append("")

# ------------------------------------------------------------------ history totals
lines += ["## 2. Included banks combined, history", "", "| Item (GHS m) | " + " | ".join(PERIODS) + " |", "| --- | " + " | ".join(["---"] * len(PERIODS)) + " |"]
for item in BIG:
    row = []
    for p in PERIODS:
        s, n = total(p, item)
        row.append(f"{s:,.0f} ({n})" if n else "-")
        csv_rows.append(["history_total", p, item, "ALL_INCLUDED", f"{s:.3f}" if n else "", n])
    lines.append(f"| {item} | " + " | ".join(row) + " |")
lines += ["", "The number in brackets is how many banks reported that line in that period. A drop means a bank is missing for that period, not that the sector shrank.", ""]

# ------------------------------------------------------------------ per bank FY2025
lines += ["## 3. Each bank, FY2025 (recomputed ratios; not bank-reported)", "",
          "| Bank | Assets | Deposits | Net loans | Equity | Profit after tax | Loans/deposits | ROE (closing equity) | Cost/income |", "| --- | --- | --- | --- | --- | --- | --- | --- | --- |"]
rows3 = []
for b in included:
    ta, dep, ln, te, pat = [H(b, "FY2025", k) for k in ("total_assets", "customer_deposits", "loans_and_advances_net", "total_equity", "profit_after_tax")]
    opx = [H(b, "FY2025", k) for k in ("staff_costs", "depreciation_amortisation", "other_operating_expenses")]
    toi = H(b, "FY2025", "operating_income_pre_impairment")
    rows3.append((ta or 0, b, ta, dep, ln, te, pat, opx, toi))
    for k, v in (("total_assets", ta), ("customer_deposits", dep), ("loans_and_advances_net", ln), ("total_equity", te), ("profit_after_tax", pat)):
        if v is not None:
            csv_rows.append(["bank_fy2025", "FY2025", k, b, f"{v:.3f}", 1])
f0 = lambda v: "-" if v is None else f"{v:,.0f}"
for _, b, ta, dep, ln, te, pat, opx, toi in sorted(rows3, reverse=True):
    ldr = f"{ln / dep * 100:.0f}%" if ln and dep else "-"
    roe = f"{pat / te * 100:.0f}%" if pat is not None and te else "-"
    cti = f"{sum(x for x in opx if x is not None) / toi * 100:.0f}%" if toi and all(x is not None for x in opx) else "-"
    lines.append(f"| {b} | {f0(ta)} | {f0(dep)} | {f0(ln)} | {f0(te)} | {f0(pat)} | {ldr} | {roe} | {cti} |")
sp, se = total("FY2025", "profit_after_tax")[0], total("FY2025", "total_equity")[0]
sl, sd = total("FY2025", "loans_and_advances_net")[0], total("FY2025", "customer_deposits")[0]
lines += ["", f"Combined: profit after tax {sp:,.0f}, equity {se:,.0f}, ROE on closing equity {sp / se * 100:.0f}%, net loans / deposits {sl / sd * 100:.0f}%. "
          f"The Bank of Ghana reports sector ROE (after tax) of {ctx['return_on_equity_after_tax']['2025-12']}% and a net-interest margin of {ctx['net_interest_margin']['2025-12']}% for Dec 2025.", ""]

# ------------------------------------------------------------------ forecast
lines += ["## 4. Included banks combined, forecast (estimates, PARTIAL sector)", "",
          "Each bank's own scenario forecast, summed. All forecasts use the shared `macro.csv`, so the scenarios are comparable. The set of banks is the same in every cell.", ""]
for item, label in (("profit_after_tax", "Profit after tax"), ("total_assets", "Total assets"), ("total_equity", "Total equity")):
    lines += [f"### {label} (GHS m)", "", "| Scenario | " + " | ".join(FYE) + " |", "| --- | " + " | ".join(["---"] * len(FYE)) + " |"]
    for sc in SCEN:
        row = []
        for y in FYE:
            vals = [fc.get((b, sc, y, item)) for b in included]
            got = [v for v in vals if v is not None]
            row.append(f"{sum(got):,.0f}" + ("" if len(got) == len(included) else f" ({len(got)}/{len(included)})"))
            csv_rows.append(["forecast_total", f"{sc}|{y}", item, "ALL_INCLUDED", f"{sum(got):.3f}" if got else "", len(got)])
        lines.append(f"| {sc} | " + " | ".join(row) + " |")
    lines.append("")
lines += ["### Where the base-case profit comes from in FY2030E (GHS m)", "", "| Bank | PAT FY2026E | PAT FY2030E | Change |", "| --- | --- | --- | --- |"]
for b in included:
    a, c = fc.get((b, "base", "FY2026E", "profit_after_tax")), fc.get((b, "base", "FY2030E", "profit_after_tax"))
    if a is not None and c is not None:
        lines.append(f"| {b} | {a:,.0f} | {c:,.0f} | {(c / a - 1) * 100:+.0f}% |" if a else f"| {b} | {a:,.0f} | {c:,.0f} | n/a |")
lines += ["", "## 5. Reading this table", "",
          "- Totals add bank-only statements. The Bank of Ghana's sector aggregates may use a different basis (for example group, or all banks including those not on our list), so coverage percentages are indicative.",
          "- Forecasts are each owner's estimate. Different owners calibrate differently, so the sum is a **sensitivity**, not a sector forecast, until the QA sweep and cross-review of all banks is complete.",
          "- See `sector/qa-sweep/report.md` for structural checks on every bank."]

with open(os.path.join(HERE, "rollup.md"), "w", encoding="utf-8") as f:
    f.write("\n".join(lines) + "\n")
with open(os.path.join(HERE, "rollup.csv"), "w", newline="", encoding="utf-8") as f:
    csv.writer(f).writerows(csv_rows)
print(f"included {len(included)} banks: {', '.join(included)}")
print(f"missing {len(missing)} of {len(ros)}")
